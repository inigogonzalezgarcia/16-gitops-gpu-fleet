# ---- Flux sync and kind --------------------------------------------------------------------------

# The lab Git server (a Gitea container on the kind network). scripts/up.sh swaps the host name for the
# container's IP when it applies sync.yaml, so it does not depend on DNS for containers.
GIT_URL = "http://fleet-git:3000/fleet/fleet.git"


def sync(c: Cluster) -> dict[str, list[dict]]:
    src = {"kind": "GitRepository", "name": "fleet"}

    def ks(name: str, wait: bool, depends: list[str] | None = None) -> dict:
        spec: dict = {"interval": "1m", "retryInterval": "20s", "timeout": "15m", "path": f"./clusters/{c.name}/{name}",
                      "prune": True, "wait": wait, "sourceRef": src}
        if depends:
            spec["dependsOn"] = [{"name": d} for d in depends]
        return {"apiVersion": "kustomize.toolkit.fluxcd.io/v1", "kind": "Kustomization",
                "metadata": {"name": name, "namespace": "flux-system"}, "spec": spec}

    return {"sync.yaml": [
        {"apiVersion": "source.toolkit.fluxcd.io/v1", "kind": "GitRepository",
         "metadata": {"name": "fleet", "namespace": "flux-system"},
         "spec": {"interval": "30s", "url": GIT_URL, "ref": {"branch": "main"}}},
        ks("operators", True),
        ks("config", False, ["operators"]),   # the CRDs come with the operators
        ks("lifecycle", True),
    ]}


def kind(c: Cluster) -> dict:
    nodes: list[dict] = [{"role": "control-plane"}]
    for p in c.pools:
        for _ in range(p.nodes):
            nodes.append({"role": "worker", "labels": {planmod.POOL_LABEL: p.name, planmod.GPU_LABEL: "true"}})
    return {"kind": "Cluster", "apiVersion": "kind.x-k8s.io/v1alpha4", "name": c.name, "nodes": nodes}


def files(f: Fleet) -> dict[str, list[dict]]:
    """Every generated file, path -> documents."""
    out: dict[str, list[dict]] = {}
    for c in f.clusters:
        for sub, fn in (("flux-system", lambda c: sync(c)), ("operators", lambda c: operators(f, c)),
                        ("config", lambda c: config(f, c)), ("lifecycle", lambda c: lifecycle(f, c))):
            for name, docs in fn(c).items():
                out[f"clusters/{c.name}/{sub}/{name}"] = docs
        out[f"kind/{c.name}.yaml"] = [kind(c)]
    return out
