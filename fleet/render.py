def _ns(name: str, privileged: bool = False) -> dict:
    meta: dict = {"name": name}
    if privileged:
        meta["labels"] = {"pod-security.kubernetes.io/enforce": "privileged"}
    return {"apiVersion": "v1", "kind": "Namespace", "metadata": meta}


def major_minor(chart_version: str) -> tuple[int, int]:
    a, b = chart_version.lstrip("v").split(".")[:2]
    return int(a), int(b)


# ---- operators ----------------------------------------------------------------------------------

def gpu_operator_values(rel: Release) -> dict:
    return {
        "operator": {"upgradeCRD": False},   # Flux replaces the CRDs (install/upgrade crds: CreateReplace)
        "driver": {
            "enabled": True,
            # one NVIDIADriver per node pool (config/) instead of one driver for the whole cluster
            "nvidiaDriverCRD": {"enabled": True, "deployDefaultCR": False},
            # nodes are upgraded one by one by the rollout controller (lifecycle/), not by the operator
            "upgradePolicy": {"autoUpgrade": False},
        },
    }


def network_operator_values(rel: Release) -> dict:
    return {
        "upgradeCRDs": False,                     # same: Flux replaces the CRDs
        # one Node Feature Discovery per cluster: the GPU Operator's. The rules that label NVIDIA NICs
        # are still deployed by this chart.
        "nfd": {"enabled": False, "deployNodeFeatureRules": True},
    }


def helm_release(name: str, namespace: str, version: str, values: dict, depends: list | None = None) -> dict:
    spec: dict = {
        "interval": "10m",
        "timeout": "10m",
        "chart": {"spec": {"chart": name, "version": version,
                           "sourceRef": {"kind": "HelmRepository", "name": "nvidia", "namespace": "flux-system"}}},
        "install": {"crds": "CreateReplace", "remediation": {"retries": 2}},
        "upgrade": {"crds": "CreateReplace", "remediation": {"retries": 2}},
        "values": values,
    }
    if depends:
        spec["dependsOn"] = depends
    return {"apiVersion": "helm.toolkit.fluxcd.io/v2", "kind": "HelmRelease",
            "metadata": {"name": name, "namespace": namespace}, "spec": spec}


def operators(f: Fleet, c: Cluster) -> dict[str, list[dict]]:
    rel = f.platform(c)
    return {
        "namespaces.yaml": [_ns("gpu-operator", True), _ns("nvidia-network-operator", True)],
        "helmrepository.yaml": [{
            "apiVersion": "source.toolkit.fluxcd.io/v1", "kind": "HelmRepository",
            "metadata": {"name": "nvidia", "namespace": "flux-system"},
            "spec": {"interval": "1h", "url": f.helm_repository},
        }],
        "gpu-operator.yaml": [helm_release("gpu-operator", "gpu-operator", rel.gpu_operator,
                                           gpu_operator_values(rel))],
        "network-operator.yaml": [helm_release("network-operator", "nvidia-network-operator", rel.network_operator,
                                               network_operator_values(rel),
                                               [{"name": "gpu-operator", "namespace": "gpu-operator"}])],
    }


# ---- per node pool --------------------------------------------------------------------------------

def nvidia_driver(f: Fleet, c: Cluster, pool) -> dict:
    """The CRD changed between GPU Operator versions: v26.7 requires `default` and moved the upgrade
    policy into the CR. The fields follow the operator version the cluster runs."""
    plat = f.platform(c)
    spec: dict = {
        "driverType": "gpu",
        "repository": "nvcr.io/nvidia",
        "image": "driver",
        "version": f.release(pool.release).driver,
        "nodeSelector": {planmod.POOL_LABEL: pool.name},
    }
    if major_minor(plat.gpu_operator) >= (26, 7):
        spec["default"] = False
        spec["upgradePolicy"] = {"autoUpgrade": False}
    return {"apiVersion": "nvidia.com/v1alpha1", "kind": "NVIDIADriver",
            "metadata": {"name": pool.name, "labels": {"fleet.lab/release": pool.release}}, "spec": spec}


def nic_node_policy(f: Fleet, c: Cluster, pool) -> dict:
    return {
        "apiVersion": "mellanox.com/v1alpha1", "kind": "NicNodePolicy",
        "metadata": {"name": pool.name, "labels": {"fleet.lab/release": pool.release}},
        "spec": {
            "nodeSelector": {planmod.POOL_LABEL: pool.name},
            "ofedDriver": {"image": "doca-driver", "repository": "nvcr.io/nvidia/mellanox",
                           "version": f.release(pool.release).doca,
                           "upgradePolicy": {"autoUpgrade": False}},
        },
    }


def config(f: Fleet, c: Cluster) -> dict[str, list[dict]]:
    return {
        "nvidiadrivers.yaml": [nvidia_driver(f, c, p) for p in c.pools],
        "nicnodepolicies.yaml": [nic_node_policy(f, c, p) for p in c.pools],
    }


